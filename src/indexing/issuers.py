"""Кто издал документ: одна сущность на орган, а не на каждую формулировку.

Проблема (живой прогон 08.11.2026, ГОСТ Р 52447—2005): в тексте орган назван и кратко
(«Росстандарт»), и полностью («Федеральное агентство по техническому регулированию и
метрологии»). Ключ сущности считался от строки, поэтому появились два regulator и две
связи document_issuance на один документ — журнал онтологии это и показал.

Решение: у органа есть КОД (rosstandart, fstek, …), и ключ считается от него. Полное и
краткое название становятся атрибутами одной сущности. Незнакомый орган не отбрасывается:
код не найден — ключ считается от нормализованной строки названия, чтобы хотя бы разные
написания одного и того же («ФСТЭК России» / «ФСТЭК») сходились.
"""

from __future__ import annotations

import re
from typing import Dict, Optional, Tuple

# Код органа → как он выглядит в графе (name, short_name).
# Коды латиницей: стабильны, не зависят от OCR и падежа.
ISSUERS: Dict[str, Tuple[str, str]] = {
    "fstek": ("ФСТЭК России", "ФСТЭК"),
    "fsb": ("ФСБ России", "ФСБ"),
    "rosstandart": ("Росстандарт", "Росстандарт"),
    "cbr": ("Банк России", "Банк России"),
    "mincifry": ("Минцифры России", "Минцифры"),
    "roskomnadzor": ("Роскомнадзор", "Роскомнадзор"),
    "minoborony": ("Минобороны России", "Минобороны"),
    "government": ("Правительство РФ", "Правительство РФ"),
    "president": ("Президент РФ", "Президент РФ"),
    "gostekhkomissiya": ("Гостехкомиссия России", "Гостехкомиссия"),
}

# Как орган называют в документах → код. Ключи — после normalize().
_ALIASES: Dict[str, str] = {
    # ФСТЭК
    "фстэк": "fstek", "фстэк россии": "fstek",
    "федеральная служба по техническому и экспортному контролю": "fstek",
    "федеральная служба по техническому и экспортному контролю россии": "fstek",
    "фстэк российской федерации": "fstek",
    "гостекхкомиссия": "gostekhkomissiya",
    # ФСБ
    "фсб": "fsb", "фсб россии": "fsb",
    "федеральная служба безопасности": "fsb",
    "федеральная служба безопасности российской федерации": "fsb",
    # Росстандарт
    "росстандарт": "rosstandart",
    "ростехрегулирование": "rosstandart",
    "госстандарт": "rosstandart",
    "госстандарт россии": "rosstandart",
    "федеральное агентство по техническому регулированию и метрологии": "rosstandart",
    "федеральное агентство по техническому регулированию и метрологии россии": "rosstandart",
    # Банк России
    "банк россии": "cbr", "цб рф": "cbr", "цб": "cbr",
    "центральный банк российской федерации": "cbr",
    # Минцифры
    "минцифры": "mincifry", "минсвязи": "mincifry",
    "министерство цифрового развития связи и массовых коммуникаций": "mincifry",
    "министерство цифрового развития связи и массовых коммуникаций российской федерации": "mincifry",
    # Роскомнадзор
    "роскомнадзор": "roskomnadzor",
    "федеральная служба по надзору в сфере связи информационных технологий и массовых коммуникаций": "roskomnadzor",
    # Минобороны
    "минобороны": "minoborony", "министерство обороны": "minoborony",
    "министерство обороны российской федерации": "minoborony",
    # Правительство и Президент
    "правительство рф": "government", "правительство российской федерации": "government",
    "президент рф": "president", "президент российской федерации": "president",
}


def normalize(value: str) -> str:
    """Строка органа для сравнения: без кавычек, пунктуации, лишних пробелов, нижний регистр."""
    s = str(value or "").strip().lower().replace("ё", "е")
    s = re.sub(r"[«»\"'`„“”]", "", s)
    s = re.sub(r"[.,;:()\[\]]", " ", s)
    s = re.sub(r"\s+", " ", s)
    return s.strip()


def code_of(*values: Optional[str]) -> Optional[str]:
    """Код органа по любому из его названий. None — орган незнакомый."""
    for raw in values:
        if not raw or not isinstance(raw, str):
            continue
        word = normalize(raw)
        if not word:
            continue
        if word in _ALIASES:
            return _ALIASES[word]
        # полное название с уточнением в конце: «… метрологии (Росстандарт)»
        for alias, code in _ALIASES.items():
            if word.startswith(alias):
                return code
    return None


def canonical(name: str = "", short_name: str = "") -> Tuple[str, str, str]:
    """Вернуть (код, name, short_name) для сущности regulator.

    Код — ключ дедупликации. Для незнакомого органа кодом служит нормализованное
    название: тогда «ФСТЭК» и «ФСТЭК России» всё равно дадут один ключ, если попали
    в один словарь алиасов, а разные органы не склеятся между собой.
    """
    code = code_of(name, short_name)
    if code:
        cname, cshort = ISSUERS[code]
        return code, cname, cshort
    base = normalize(short_name) or normalize(name)
    return base, (name or short_name or "").strip(), (short_name or "").strip()
