"""Настройки обработки таблиц: что включено, что выключено, где границы.

Зачем отдельный namespace, а не константы в коде: табличный стек не бесплатный.
Строковые векторы — это эмбеддинг на КАЖДУЮ строку таблицы (внешний вызов + точки в
Qdrant), второй экстрактор (pdfplumber/Camelot) — это время разбора. Поэтому:

- дешёвая часть (разметка `table_id`, строки в SQL, оценка качества, нормализация)
  идёт всегда, когда в документе есть таблицы, и ничего не стоит;
- дорогая часть (векторы строк, второй экстрактор) — отдельными переключателями,
  по умолчанию включена там, где окупается, и выключается из админки без пересборки;
- документов БЕЗ таблиц это не касается вовсе — на них стек не работает и не тратит время.

Значения — в config_store (namespace `tables`, ключ `config`), читаются через
`get_tables_config()`: неполный или битый конфиг не должен ломать обработку,
поэтому недостающие поля берутся из DEFAULTS, а ошибка чтения = defaults.
"""

from __future__ import annotations

import logging
from typing import Any, Dict

logger = logging.getLogger(__name__)

CONFIG_NS = "tables"
CONFIG_KEY = "config"

# Значения по умолчанию с обоснованием. Меняются из админки (POST /admin/models/tables)
# без пересборки образа: это настройка, а не код.
DEFAULTS: Dict[str, Any] = {
    # Стек таблиц включён. Выключение возвращает поведение до внедрения (таблицы идут
    # только как markdown-сегменты, без разметки и без строчного слоя).
    "enabled": True,

    # Табличный сегмент — всегда ОТДЕЛЬНЫЙ чанк: не склеивается с текстом страницы и не
    # режется пополам. Иначе строка из одной таблицы может попасть в один вектор с текстом
    # или с другой таблицей, и «не смешивай строки разных таблиц» нарушается.
    "atomic_chunks": True,

    # Вектор на КАЖДУЮ строку таблицы. Самая дорогая часть: один вызов эмбеддинга на строку.
    # Даёт точные ответы «какая цена у X», «позиции дороже 10 000».
    "row_vectors": True,

    # Групповые векторы (по group_size строк): дешевле строковых, отвечают на вопросы
    # «что за позиции в таблице», «опиши состав спецификации».
    "group_vectors": True,
    "group_size": 20,

    # Вектор-сводка таблицы (шапка + подпись + первые строки, БЕЗ вызова LLM): искать таблицу
    # как целое — «спецификация оборудования, страница 7».
    "summary_vector": True,

    # Ограничение на строковые векторы для очень больших таблиц: выше лимита индексируем
    # только группы и сводку. Защита от документа с таблицей на 5000 строк.
    "max_rows_for_row_vectors": 200,

    # Таблицы с качеством ниже порога не участвуют в строчном поиске (мусор не должен
    # отравлять выдачу), но остаются в document_tables для показа.
    "min_quality_for_rows": 0.35,

    # Второй экстрактор запускается ТОЛЬКО если качество PyMuPDF ниже порога —
    # в обычном случае он не тратит время.
    "pdfplumber_fallback": True,
    "pdfplumber_min_quality": 0.5,

    # Camelot — третий экстрактор, тянет ghostscript/opencv. По умолчанию ВЫКЛ.
    "camelot_fallback": False,

    # Вычисления по таблицам (SQL) в чате: вопрос про сумму/максимум/фильтр уходит в
    # строковый слой Postgres, а не считается моделью по кускам текста.
    "sql_enabled": True,
    "sql_max_rows": 500,        # предел строк в ответе SQL
    "sql_timeout_ms": 5000,     # предел времени запроса
}


def _merge_defaults(raw: Any) -> Dict[str, Any]:
    """Слить прочитанный конфиг с дефолтами: неизвестные ключи игнорируем, пропуски — из DEFAULTS."""
    cfg = dict(DEFAULTS)
    if isinstance(raw, dict):
        for key, value in raw.items():
            if key in DEFAULTS and value is not None:
                cfg[key] = value
    return cfg


def get_tables_config() -> Dict[str, Any]:
    """Текущие настройки таблиц. Ошибка чтения настроек не должна ломать обработку."""
    try:
        from src.api.services.config_store import config_store

        raw = config_store.get(CONFIG_NS, CONFIG_KEY)
        return _merge_defaults(raw)
    except Exception as e:  # pragma: no cover - зависит от внешней БД
        logger.warning(f"[tables] настройки прочитать не удалось ({e}), работаю на значениях по умолчанию")
        return dict(DEFAULTS)


def tables_enabled() -> bool:
    """Включён ли табличный стек (короткий путь для конвейера обработки)."""
    return bool(get_tables_config().get("enabled", True))
