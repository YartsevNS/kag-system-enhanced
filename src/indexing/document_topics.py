RUBRIC_CODES: tuple = tuple(RUBRICS)


def codes() -> List[str]:
    """Все коды рубрик в порядке словаря."""
    return list(RUBRIC_CODES)


def is_valid(code: Optional[str]) -> bool:
    """Код есть в словаре (пустая строка и None — не рубрики)."""
    return bool(code) and code in RUBRICS


def title(code: str) -> str:
    """Человеческое название рубрики; для неизвестного кода — сам код (честно, без выдумки)."""
    return (RUBRICS.get(code) or {}).get("title", code or "")


def normalize(codes_in) -> List[str]:
    """Привести список рубрик к кодам словаря: неизвестное отбрасываем, дубли убираем, порядок словаря.

    Отбрасывать, а не складывать в `other`: «незнакомый код» и «тема не определена» — разные вещи,
    и смешивать их значит потерять признак ошибки разметки.
    """
    if codes_in is None:
        return []
    if isinstance(codes_in, str):
        codes_in = [codes_in]
    seen = []
    for c in codes_in:
        c = str(c or "").strip().lower()
        if is_valid(c) and c not in seen:
            seen.append(c)
    return [c for c in RUBRIC_CODES if c in seen]


def as_list() -> List[Dict[str, str]]:
    """Плоский список для интерфейса и API: [{code, title, definition, aspects}]."""
    return [
        {"code": code, "title": meta.get("title", code),
         "definition": meta.get("definition", ""), "aspects": meta.get("aspects", "")}
        for code, meta in RUBRICS.items()
    ]


def vocabulary_line() -> str:
    """Строка кодов для промптов: «a, b, c» — как ждёт анализатор документов."""
    return ", ".join(RUBRIC_CODES)
