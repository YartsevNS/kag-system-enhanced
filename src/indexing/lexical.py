"""Русский лексический анализ для sparse-ветки поиска (BM25).

Зачем модуль: sparse-векторы строились как CRC32 от сырых токенов — без
стемминга, без IDF, без стоп-слов. Для русского это почти бесполезно: запрос
«получение вычета» не находил чанк со словом «получить», а частотные «и/в/на»
давали совпадение по любому тексту. На замере 2026-09-12 гибрид проигрывал
плотному поиску (MRR 0.802 против 0.821) и портил слабый кейс — ветку
пришлось выключить.

Что делаем здесь:
  - нормализация ё→е (в русских текстах пишут по-разному, для поиска это одно слово);
  - стоп-слова (частотные предлоги/местоимения/союзы) — они не несут смысла
    и дают ложные совпадения по любому фрагменту;
  - лёгкий суффиксный стеммер: «получение»/«получить»/«получения» → «получ».
    Полноценный Snowball точнее, но требует зависимости (nltk/pymorphy),
    а значит пересборки тяжёлого kag-base и добавочных данных в офлайн-бандл.
    Суффиксный стеммер детерминирован, без зависимостей и покрывает основную
    причину промахов — падежные/числовые формы;
  - числа и короткие токены не стеммим: «7403-У», «2026», «ГОСТ» должны
    находиться точно.

Совместимость: id токена = crc32(стем) в том же пространстве, что был раньше,
но значения для слов изменились → sparse-векторы существующих документов надо
пересчитать: `scripts/reindex_sparse.py` (локальный пересчёт, без эмбеддингов
и LLM, через Qdrant update_vectors по qdrant_point_id).
"""

from __future__ import annotations

import re
import zlib
from typing import Dict, List

# Стоп-слова русского языка: предлоги, союзы, местоимения, частицы, служебные
# глаголы. Список намеренно короткий — только то, что встречается почти в любом
# фрагменте и потому не различает документы.
STOPWORDS_RU = frozenset("""
и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по
только ее мне было вот от меня еще нет о из ему теперь когда даже ну вдруг ли
если уже или ни быть был него до вас нибудь опять уж вам ведь там потом себя
ничего ей может они тут где есть надо ней для мы тебя их чем была сам чтоб без
будто чего раз тоже себе под будет ж тогда кто этот того потому этого какой
совсем ним здесь этом один почти мой тем чтобы нее сейчас были куда зачем всех
никогда можно при наконец два об другой хоть после над больше тот через эти нас
про всего них какая много разве три эту моя впрочем хорошо свою этой перед
иногда лучше чуть том нельзя такой им более всегда конечно всю между это также
свои который которая которое которые которая поэтому если только они
является являются быть был была было были будет будут имеет имеют можно нужно
данном данной данном также так как таким таким образом согласно
""".split())

# Суффиксы от длинных к коротким: первое совпадение выигрывает.
_SUFFIXES: tuple[str, ...] = (
    "иями", "ями", "ами", "ией", "иях", "иям", "ием", "ией",
    "ого", "его", "ому", "ему", "ыми", "ими", "ей", "ой", "ый", "ий", "ая", "яя",
    "ое", "ее", "ые", "ие", "ым", "им", "ом", "ем", "ах", "ях", "ам", "ям",
    "ов", "ев", "ью", "ию", "ия", "ья", "ье", "ем",
    "ы", "и", "а", "я", "о", "е", "у", "ю", "ь", "й",
)

# Минимальная длина основы: «дома» → «дом», но «оси»/«уши» не трогаем.
MIN_STEM_LEN = 3

# Усечение длинных основ — приём русского IR. Суффиксный стеммер не сводит
# отглагольное существительное с инфинитивом («получение» → «получен», а
# «получить» → «получит»), поэтому длинные слова дополнительно режем до
# 5 символов: «получен»/«получит» → «получ». Точность слегка страдает
# (возможны коллизии по префиксу), но IDF в Qdrant давит частые совпадения,
# а полнота словарных совпадений растёт заметно.
LONG_WORD_LEN = 7
STEM_TRUNCATE_LEN = 5

_TOKEN_RE = re.compile(r"[a-zа-яё0-9]+")


def normalize(text: str) -> str:
    """Привести текст к нижнему регистру и унифицировать ё."""
    return (text or "").lower().replace("ё", "е")


def stem_ru(word: str) -> str:
    """Лёгкий стеммер: отрезать самый длинный подходящий суффикс.

    Числа и токены с цифрами не трогаем (номера документов, годов, пунктов).
    Слова короче MIN_STEM_LEN символов остаются как есть. Длинные слова
    (LONG_WORD_LEN+) усекаются до STEM_TRUNCATE_LEN символов основы — чтобы
    сходились разные части речи («получение»/«получить» → «получ»).
    """
    w = word
    if not w or any(ch.isdigit() for ch in w):
        return w
    stem = w
    for suffix in _SUFFIXES:
        if w.endswith(suffix) and len(w) - len(suffix) >= MIN_STEM_LEN:
            stem = w[: len(w) - len(suffix)]
            break
    if len(w) > LONG_WORD_LEN and len(stem) > STEM_TRUNCATE_LEN:
        stem = stem[:STEM_TRUNCATE_LEN]
    return stem


def tokenize_lexical(text: str) -> List[str]:
    """Токены для лексического поиска: нормализация → стоп-слова → стемминг."""
    out: List[str] = []
    for raw in _TOKEN_RE.findall(normalize(text)):
        if len(raw) == 1:
            continue                      # одиночные буквы — шум
        if raw in STOPWORDS_RU:
            continue
        out.append(stem_ru(raw))
    return out


def sparse_terms(text: str) -> Dict[str, int]:
    """{стем: частота} — для отладки и тестов."""
    freq: Dict[str, int] = {}
    for token in tokenize_lexical(text):
        freq[token] = freq.get(token, 0) + 1
    return freq


def sparse_vector(text: str) -> Dict[str, list]:
    """Sparse-вектор Qdrant: {"indices": [crc32(стем)], "values": [частота]}.

    id = crc32(стем) — стабилен между документами и запросами, поэтому векторы
    чанков и запроса согласованы (это то, что нужно для BM25-ветки).
    """
    freq: Dict[int, int] = {}
    for token, count in sparse_terms(text).items():
        tid = zlib.crc32(token.encode("utf-8")) & 0x7FFFFFFF
        freq[tid] = freq.get(tid, 0) + count
    return {"indices": list(freq.keys()), "values": list(freq.values())}
