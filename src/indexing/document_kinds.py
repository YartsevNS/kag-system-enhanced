KIND_CODES: tuple = tuple(KINDS)


def codes() -> List[str]:
    """Все коды видов в порядке словаря."""
    return list(KIND_CODES)


def is_valid(code: str) -> bool:
    """Код есть в словаре (пустая строка и None — не виды)."""
    return bool(code) and code in KINDS


def title(code: str) -> str:
    """Полное человеческое название вида; для неизвестного кода — сам код."""
    return (KINDS.get(code) or {}).get("title", code or "")


def short(code: str) -> str:
    """Короткая подпись для плашки/миниатюры; для неизвестного кода — сам код."""
    return (KINDS.get(code) or {}).get("short", code or "")


def group_of(code: str) -> str:
    return (KINDS.get(code) or {}).get("group", "")


def as_list() -> List[Dict[str, str]]:
    """Плоский список для интерфейса и API: [{code, title, short, group, group_title, definition}]."""
    out = []
    for code, meta in KINDS.items():
        out.append({
            "code": code,
            "title": meta.get("title", code),
            "short": meta.get("short", code),
            "group": meta.get("group", ""),
            "group_title": GROUPS.get(meta.get("group", ""), ""),
            "definition": meta.get("definition", ""),
        })
    return out


def vocabulary_line() -> str:
    """Строка кодов для промптов и проверок: «a, b, c» — как ждёт анализатор документов."""
    return ", ".join(KIND_CODES)
