"""Уточнение типов сущностей правилами: без модели, детерминированно.

Зачем: замеры показали, что модель путает типы там, где ответ очевиден и проверяем формой записи.
Живые примеры из замера: обозначение пункта «А.1.1» получило тип `document_ref`, а «ключ шифрования» —
`legal_term`. От этого страдают обе задачи: связь от документа к «пункту, названному документом»
попадает под неверное правило допустимых пар, а поиск по типу документа находит не то.

Правило простое: если запись имеет строгую форму — тип известен без модели.
  * номер стандарта (ГОСТ, ГОСТ Р, СП, СНиП, СанПиН) → `standard`;
  * ссылка на пункт/раздел/таблицу/приложение, а также голый номер вида «А.1.1» или «5.2.1» → `clause`;
  * номер закона («152-ФЗ»), реквизиты акта («Приказ № 17», «Указание Банка России от 15.06.2026 № 7369-У»)
    → `document_ref`;
  * дата в строгой форме → `date`.

Ничего не угадываем: если форма не опознана, тип остаётся прежним (`refine_type` вернёт его же).

Модуль без внешних зависимостей: используется и в конвейере, и в приборах, и в тестах.
"""

from __future__ import annotations

import re

# Номер стандарта: ГОСТ, ГОСТ Р, ГОСТ Р ИСО/МЭК, СП, СНиП, СанПиН.
STANDARD = re.compile(
    r"^\s*(?:ГОСТ(?:\s+Р)?(?:\s+ИСО\s*/\s*МЭК)?|СП|СНиП|СанПиН|СН)\s*"
    r"\d{1,5}(?:[.\-/]\d{1,4})*(?:\s*-\s*\d{2,4})?\s*$",
    re.IGNORECASE,
)
# Ссылка на пункт со словом: «п. 5.2.1», «раздел 6», «таблица 3», «приложение А».
# Английские формы добавляем отдельно: в корпусе есть документы на английском (выгрузки SEC),
# и там «Section 6.7» — это пункт, «Exhibit 10.39» — документ. Без этих форм такие ссылки
# получали тип document_ref, и связь «документ содержит пункт» отбраковывалась как недопустимая
# (проверено на живом прогоне 10.10.2026: 9 связей REFERENCES → HAS_CLAUSE у судьи).
CLAUSE_WORDED = re.compile(
    r"^\s*(?:п\.|пп\.|пункт|подпункт|раздел|разд\.|глава|таблица|приложение|ст\.|статья|часть|ч\.|"
    r"section|article|clause|paragraph|appendix|schedule|item)"
    r"\s*№?\s*[0-9А-ЯЁA-Z]{1,3}(?:[.\-][0-9А-ЯЁA-Z]{1,3}){0,4}\s*$",
    re.IGNORECASE,
)
# Реквизит-ссылка на приложение/выставку: «Exhibit 10.39», «Appendix B».
EXHIBIT = re.compile(r"^\s*(?:exhibit|annex|приложение)\s+[0-9A-ZА-ЯЁ][0-9A-ZА-ЯЁ.\-]*\s*$", re.IGNORECASE)
# Голый номер пункта: «5.2.1», «А.1.1», «4.4». Требуем минимум две части через точку.
CLAUSE_BARE = re.compile(r"^\s*[0-9А-ЯЁA-Z]{1,3}(?:\.[0-9А-ЯЁA-Z]{1,3}){1,4}\s*$")
# Номер закона: 152-ФЗ, 44-ФЗ.
LAW = re.compile(r"^\s*\d{2,3}\s*-\s*ФЗ\s*$", re.IGNORECASE)
# Реквизиты акта: «Приказ № 17», «Указание Банка России от 15.06.2026 № 7369-У».
ACT = re.compile(
    r"^\s*(?:приказ|положение|распоряжение|указание|постановление|письмо|инструкция|методика|указ|"
    r"федеральный\s+закон|решение|определение)\b.*(?:№\s*\S+|\d{2,3}\s*-\s*ФЗ)\s*$",
    re.IGNORECASE,
)
DATE = re.compile(r"^\s*(?:\d{1,2}[.\-/]\d{1,2}[.\-/]\d{4}|\d{4}-\d{2}-\d{2})\s*$")

CLAUSE_TYPES = {"clause"}
STANDARD_TYPES = {"standard"}

# Версия правил типизации. Поднимать при любом изменении списка форм: эти правила правят типы ДО
# записи в граф, поэтому от них зависит ключ кэша извлечения (иначе старые типы вернутся из кэша).
# 2 — добавлены английские формы («Section 6.7» → пункт, «Exhibit 10.39» → документ).
ENTITY_RULES_EPOCH = 2


def refine_type(name: str, current_type: str = "") -> str:
    """Вернуть уточнённый тип сущности. Если форма не опознана — прежний тип."""
    n = (name or "").strip()
    if not n:
        return current_type
    t = (current_type or "").strip().lower()

    if STANDARD.match(n):
        return "standard"
    if LAW.match(n) or ACT.match(n):
        return "document_ref"
    if CLAUSE_WORDED.match(n) or CLAUSE_BARE.match(n):
        # Голый номер вида «5.2.1» — почти всегда ссылка на пункт, но не «34.10» (номер стандарта
        # без слова «ГОСТ» модель отдаёт редко, а такие обозначения узнаются по контексту в тексте).
        return "clause"
    if EXHIBIT.match(n):
        # «Exhibit 10.39» — это документ (приложение к отчётности), а не пункт.
        return "document_ref"
    if DATE.match(n):
        return "date"
    return current_type or ""


def refine_entities(entities: list[dict]) -> tuple[list[dict], list[tuple]]:
    """Уточнить типы у списка сущностей извлечения.

    Возвращает (исправленный список, список правок вида (имя, было, стало)) — правки нужны для
    журнала: видно, где модель ошиблась и правило её поправило.
    """
    out = []
    changes = []
    for e in entities or []:
        name = e.get("name")
        was = (e.get("type") or "").strip().lower()
        now = refine_type(str(name or ""), was)
        if now and now != was:
            changes.append((str(name), was, now))
            e = {**e, "type": now}
        out.append(e)
    return out, changes


if __name__ == "__main__":  # самопроверка на живых примерах из замера
    samples = [
        ("ГОСТ Р 57580.1-2017", "legal_term"), ("ГОСТ Р ИСО/МЭК 27001-2021", "legal_term"),
        ("А.1.1", "document_ref"), ("5.2.1", "legal_term"), ("п. 4.4", "legal_term"),
        ("таблица 3", "legal_term"), ("152-ФЗ", "legal_term"),
        ("Указание Банка России от 15.06.2026 № 7369-У", "legal_term"),
        ("Приказ ФСТЭК России № 17", "legal_term"),
        ("15.06.2026", "legal_term"),
        ("ключ шифрования", "legal_term"),      # форма не опознана — тип не меняем
        ("Банк России", "organization"),
    ]
    for name, was in samples:
        now = refine_type(name, was)
        mark = "ПРАВКА" if now != was else "как есть"
        print(f"  {name[:52]:54s} {was:14s} → {now:14s} {mark}")
