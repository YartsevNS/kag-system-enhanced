PAGE = "kag:словари"
CRED = "/root/kag-agent-cred.txt"
URL = "http://localhost:8080/lib/exe/xmlrpc.php"

TEXT = """====== Словари: что это, зачем и почему их нельзя менять просто так ======

Страница отвечает на три вопроса: **какие у нас словари**, **зачем каждый** и **что произойдёт, если
поменять словарь не подумав**. Главное следствие, ради которого страница и написана: правка словаря
связей обнуляет кэш извлечения, и следующая обработка корпуса снова платит за вызовы модели.

===== 1. Какие словари есть и где они лежат =====

^ Словарь ^ Что задаёт ^ Где живёт ^ Правится из админки? ^
| **Типы связей и допустимые пары** | какие отношения могут быть между сущностями (например «документ ссылается на стандарт») | КОД: ''src/indexing/graph_ontology.py'' | НЕТ |
| **Типы сущностей** | что вообще может быть узлом: документ, человек, организация, стандарт, пункт, дата, сумма, место, событие, юр. термин | КОД: ''graph_ontology.py'' + пресеты в ''entity_extractor.py'' | НЕТ |
| **Виды документов (словарь v0)** | вид документа: стандарт, регламент, приказ, публикация, закон… | база + ''docs/plans/ontology-v0-draft.md'' | частично (через разметку) |
| **Фасеты** | закрытые перечни: предмет защиты, нормативная сила | база (''documents.facets'') | ДА |
| **Темы (рубрики)** | о чём документ — fасетная классификация | база (''documents.rubrics'') | ДА |
| **Алиасы сущностей** | сведение разных написаний к одному: «ЦБ», «Банк России», «ЦБ РФ» → «Банк России» | база (пары «алиас → каноническое») | ДА — это и есть страница «Словарь» в админке |
| **Общие свойства онтологии** | единый список имён свойств факта: наименование, номер, дата, издатель, статус, версия схемы… | КОД: ''src/indexing/shared_properties.py'' | нет, показывается в админке |

Проще говоря: **алиасы, темы и фасеты правятся из интерфейса**, потому что они лежат в базе и не
меняют правила извлечения. **Типы связей и сущностей правятся только в коде**, потому что они задают
задание модели и проверку фактов.

===== 2. Зачем каждый словарь =====

**Типы связей с допустимыми парами.** Без закрытого списка модель придумывает типы и сваливает всё в
одну мусорку: на замере 58% связей оказались безымянными «связано с». Словарь задаёт: вот эти типы, и
вот такие пары «тип источника → тип цели» допустимы. Всё, что не проходит проверку, в граф не пишется —
и это правильно: лучше меньше, но проверяемых фактов.

**Типы сущностей.** Нужны, чтобы «Банк России» был организацией, а не «просто строкой», и чтобы
допустимые пары имели смысл: «подписано» — это документ и человек, а не место и дата.

**Алиасы.** LLM называет один объект по-разному (34% дублей в типичном графе). Алиасы сводят написания
к одному узлу, и связи не рвутся.

**Общие свойства.** Один список имён для всех фактов: иначе у каждого факта своё название поля,
фильтры не складываются, а выгрузки пишутся под каждое имя отдельно.

===== 3. Почему типы связей не правятся из админки =====

Потому что тип связи — это не настройка отображения, а часть **задания модели** и **проверки при
записи**. Изменение словаря затрагивает три вещи одновременно:

  1. текст задания, который видит модель при извлечении;
  2. проверку тройки «тип — связь — тип» перед записью в граф;
  3. ключ кэша извлечения, от которого зависит, будет ли модель вызвана заново.

Правка «на лету» из интерфейса означала бы, что у половины корпуса один словарь, у половины другой, и
сравнивать результаты нельзя. Поэтому словарь меняется в одном месте (''graph_ontology.py''), версия
поднимается осознанно, и только после этого запускается переобработка.

===== 4. Что произойдёт, если поменять словарь =====

**Главное: обнулится кэш извлечения.** Когда модель разбирает фрагмент, её ответ сохраняется в базу.
Ключ записи включает версию онтологии. Поднял версию — ключ другой — старые ответы не подходят, и
модель вызывается заново по ВСЕМУ тексту.

Цена по нашему корпусу: около 9 тысяч фрагментов, на каждый до двух обращений к модели. Один прогон
всего корпуса — это часы работы стенда и деньги за вызовы. Поэтому:

  * версию поднимать **пачкой** накопленных правок, а не после каждой запятой;
  * проверять правку **на выборке 3–5 документов**, а не на всём корпусе;
  * полную пересборку делать **один раз**, когда конвейер заморожен перед приёмкой.

**Второе: старые коды остаются читаемыми.** Прежние названия (''SIGNED_BY'', ''HAS_CLAUSE'',
''RELATED_TO'' …) перечислены в переводе ''MIGRATION'' и остаются допустимыми. Уже записанные связи
видны и не подменяются, а при пересборке те же факты записываются уже каноническими кодами.

**Третье: если забыть поднять версию** — правка молча не подействует. Модель вернёт старые ответы из
кэша, и будет казаться, что ничего не изменилось. Так уже было 10.10.2026: поправили правила, а все
связи пришли из кэша. Поэтому в кэш добавлен ещё и хеш текста задания: правка формулировки теперь
тоже сбрасывает кэш.

===== 5. Почему типы связей взяты из стандартов =====

Наши типы связей — это коды из опубликованных словарей, а не выдуманные названия:

  * **STIX 2.1** (OASIS, безопасность): ''part-of'', ''member-of'', ''located-at'', ''attributed-to'', ''authored-by'', ''derived-from'', ''targets'', ''indicates'', ''mitigates'';
  * **ELI** (ЕС, правовые документы): ''amends'', ''repeals'', ''corrects'', ''consolidates'';
  * **Dublin Core Terms** (документы): ''references'', ''has-part'', ''is-version-of'', ''replaces'', ''requires'';
  * **своё** (в стандартах этого нет): ''signed-by'', ''issued-by'', ''dated'', ''has-amount'', ''defines'', ''applies-to'', ''establishes-requirement'', ''related-to''.

Зачем: у каждого типа есть источник, который можно предъявить заказчику, и появляется путь выгрузки в
отраслевые форматы. У RAG-систем (GraphRAG, LightRAG) закрытого словаря нет вовсе — извлечение там
свободное, брать у них нечего. Полная таблица соответствия:
''docs/plans/ontology-canonical-mapping.md''.

===== 6. Порядок изменения словаря (обязательный) =====

  1. Правка в ''src/indexing/graph_ontology.py'' — список ''RELATIONS'' и/или перевод ''MIGRATION''.
  2. Поднять ''ONTOLOGY_EPOCH'' — иначе кэш вернёт прежние ответы.
  3. Проверка на выборке 3–5 документов: сколько связей проходит, какие пары отбрасываются.
  4. Только после этого — решение о пересборке (и лучше один раз, на замороженном конвейере).

===== 7. Где смотреть состояние словарей сейчас =====

  * в админке есть страница состояния словарей (фасеты, темы, общие свойства, схема графа) — только просмотр;
  * страница «Словарь» в админке правит **алиасы сущностей** (синонимы названий) и умеет применять их к графу;
  * типы связей и допустимые пары меняются в коде, описанным выше порядком.

Разбор самих типов и того, как строится граф, — на странице «Как работает система» (''kag:как-работает'').
"""


def creds(path: str) -> tuple[str, str]:
    user = password = ""
    with open(path, encoding="utf-8") as f:
        for line in f:
            low = line.lower()
            if low.startswith("пользовател"):
                user = line.split(":", 1)[1].strip()
            elif low.startswith("пароль"):
                password = line.split(":", 1)[1].strip()
    return user, password


class CookieTransport(xmlrpc.client.Transport):
    """Транспорт с сохранением печенек: без него вход проходит, а запись страницы нет (401)."""

    def __init__(self) -> None:
        super().__init__()
        import http.cookiejar
        import urllib.request
        self.jar = http.cookiejar.CookieJar()
        self.opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(self.jar))

    def request(self, host, handler, request_body, verbose=False):
        import urllib.request
        req = urllib.request.Request(f"http://{host}{handler}", data=request_body,
                                     headers={"Content-Type": "text/xml", "User-Agent": "kag-agent/1.0"})
        with self.opener.open(req, timeout=60) as resp:
            self.verbose = verbose
            return self.parse_response(resp)


def main() -> int:
    user, password = creds(CRED)
    if not user or not password:
        print("не разобрал учётные данные в", CRED, file=sys.stderr)
        return 2
    proxy = xmlrpc.client.ServerProxy(URL, allow_none=True, transport=CookieTransport())
    if not proxy.dokuwiki.login(user, password):
        print("вход не выполнен", file=sys.stderr)
        return 3
    ok = proxy.wiki.putPage(PAGE, TEXT, {"sum": "словари: состав, зачем, почему правка обнуляет кэш и требует пересборки"})
    print("страница записана:", PAGE, "| ответ:", ok)
    return 0 if ok else 4


if __name__ == "__main__":
    raise SystemExit(main())
