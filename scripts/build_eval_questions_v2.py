# Эталоны, которых больше нет в корпусе (проверено scripts/validate_eval_targets_template.py
# на стенде). Вопрос v1 №3 «внешнеторговые бартерные сделки» ссылался на b60f0345 — документ
# удалён вместе с сиротами, поэтому вопрос физически недостижим, и все прошлые метрики
# включали его как гарантированный промах. Помечаем контрольным, а не молча считаем промахом.
DEAD_TARGETS = {3: "b60f0345-f673-4751-8610-d5011bbdf7b0"}

CONTROL = [
    "какая погода в Москве завтра",
    "расписание поездов Москва Казань",
    "рецепт борща с говядиной",
]


def main():
    v1 = json.loads(V1.read_text(encoding="utf-8"))
    id_map = json.loads(ID_MAP.read_text(encoding="utf-8"))

    def full(prefix: str) -> str:
        got = id_map.get(prefix)
        if not got:
            raise SystemExit(f"нет полного id для префикса {prefix} — обновите scripts/eval_id_map.json")
        return got

    questions = list(v1.get("questions") or [])
    base = len(questions)

    # Примечание: эталоны, которых больше нет в корпусе, помечает отдельный шаг
    # scripts/mark_missing_targets.py по результату проверки на стенде
    # (здесь БД недоступна, а сверять надо с фактическим составом документов).
    for q, pref, note in NEW_SINGLE:
        questions.append({
            "query": q,
            "relevant_document_ids": [full(pref)],
            "relevant_chunk_ids": [],
            "notes": f"v2 (проверено владельцем по формулировке): {note}",
        })
    for q, prefs, note in NEW_COMPARE:
        questions.append({
            "query": q,
            "relevant_document_ids": [full(p) for p in prefs],
            "relevant_chunk_ids": [],
            "notes": f"v2 сравнительный: {note}",
        })
    for q in CONTROL:
        questions.append({
            "query": q,
            "relevant_document_ids": [],
            "relevant_chunk_ids": [],
            "control": True,
            "notes": "контрольный: ответа в корпусе нет — смотрим top-1 score",
        })

    # помечаем вопросы с исчезнувшими эталонами контрольными
    for idx, dead_id in DEAD_TARGETS.items():
        _q = questions[idx - 1]
        _ids = list(_q.get("relevant_document_ids") or [])
        if dead_id in _ids:
            _q["control"] = True
            _q["relevant_document_ids"] = []
            _q["notes"] = (
                f"эталон {dead_id[:8]} отсутствует в корпусе (удалён вместе с сиротами) — "
                "переведён в контрольный: прошлые метрики включали его как промах"
            )

    doc = {
        "description": (
            f"Набор для оценки retrieval, версия 2 (2026-09-13). Первые {base} вопросов — "
            "исторический набор v1 (метрики по нему сравнимы с прошлыми прогонами). "
            "Формулировки новых вопросов просмотрены владельцем; в notes — имя файла и название "
            "документа корпуса, на который опирается эталон (сам эталон — relevant_document_ids)."
        ),
        "k_values": v1.get("k_values") or [1, 3, 5, 10],
        "legacy_count": base,
        "questions": questions,
    }
    V2.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"  v1: {base} | одиночных новых: {len(NEW_SINGLE)} | сравнительных: {len(NEW_COMPARE)} | "
          f"контрольных: {len(CONTROL)} | всего: {len(questions)}")


if __name__ == "__main__":
    main()
