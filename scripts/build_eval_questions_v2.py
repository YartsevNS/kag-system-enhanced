def main():
    v1 = json.loads(V1.read_text(encoding="utf-8"))
    questions = list(v1.get("questions") or [])
    base = len(questions)

    for q, did, note in NEW_SINGLE:
        questions.append({
            "query": q,
            "relevant_document_ids": [did],
            "relevant_chunk_ids": [],
            "notes": f"черновик v2: {note}",
        })

    for q, ids, note in NEW_COMPARE:
        questions.append({
            "query": q,
            "relevant_document_ids": list(ids),
            "relevant_chunk_ids": [],
            "notes": f"черновик v2 (сравнительный): {note}",
        })

    for q in CONTROL:
        questions.append({
            "query": q,
            "relevant_document_ids": [],
            "relevant_chunk_ids": [],
            "control": True,
            "notes": "контрольный: ответа в корпусе нет — смотрим top-1 score, а не попадание",
        })

    doc = {
        "description": (
            "Набор для оценки retrieval, версия 2 (2026-09-13). Первые %d вопросов — исторический "
            "набор v1 (метрики по нему сравнимы с прошлыми прогонами). Далее: вопросы по конкретным "
            "документам (нужен черновой просмотр владельцем), сравнительные (несколько relevant_document_ids) "
            "и контрольные (ответа нет — измеряем уверенность системы на неотвечаемом вопросе)."
            % base
        ),
        "k_values": v1.get("k_values") or [1, 3, 5, 10],
        "legacy_count": base,
        "questions": questions,
    }
    V2.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8")

    singles = len(NEW_SINGLE)
    print(f"  v1 вопросов: {base}")
    print(f"  добавлено: одиночных {singles}, сравнительных {len(NEW_COMPARE)}, контрольных {len(CONTROL)}")
    print(f"  всего в v2: {len(questions)}")
    print(f"  файл: {V2}")


if __name__ == "__main__":
    main()
